<?php
namespace App\Controllers;

use App\Core\Controller;
use App\Models\Article;

class ExcelImportController extends Controller {
    private Article $articleModel;

    public function __construct() {
        $this->articleModel = new Article();
    }

    public function template(): void {
        $year = isset($_GET['year']) ? (int)$_GET['year'] : (int)date('Y');
        if ($year <= 2000) $year = (int)date('Y');
        $filename = "cathedral_article_master_template_{$year}.csv";
        header('Content-Type: text/csv; charset=utf-8');
        header('Content-Disposition: attachment; filename="' . $filename . '"');

        $output = fopen('php://output', 'w');
        // Fetch real categories from Master
        $masterCategories = $this->articleModel->getCategories();
        
        // Header columns based on Article Master (Article No is omitted; auto-generated by the system upon import)
        fputcsv($output, [
            'Tag No', 
            'Year', 
            'Article Name', 
            'Category', 
            'Estimated Value (BHD)', 
            'Reserve Price (BHD)', 
            'Donor Name', 
            'Donor Roll No', 
            'Donor Phone', 
            'Donor CPR', 
            'Description'
        ]);
        
        // Sample rows with categories directly from Master
        $cat1 = $masterCategories[0] ?? 'General';
        $cat2 = $masterCategories[1] ?? 'Traditional & Brass';
        $cat3 = $masterCategories[2] ?? 'Jewellery';
        $cat4 = $masterCategories[3] ?? 'Food & Delicacy';
        $cat5 = $masterCategories[4] ?? 'Handicrafts';

        fputcsv($output, ["TAG-001", $year, "Nilavilakku Traditional Brass Lamp", $cat2, "85.000", "85.000", "George Varghese", "1042", "39123456", "850123456", "Heavy 5-step prayer lamp donated for cathedral auction"]);
        fputcsv($output, ["TAG-002", $year, "Gold Sovereign 22K Coin", $cat3, "220.000", "220.000", "Anonymous Well-Wisher", "", "", "", "Donated for cathedral harvest auction"]);
        fputcsv($output, ["TAG-003", $year, "Harvest Organic Spices & Honey Box", $cat4, "40.000", "35.000", "St. Thomas Prayer Group", "2055", "36541234", "", "Cardamom, mountain pepper, forest honey"]);
        fputcsv($output, ["TAG-004", $year, "Handwoven Kasavu Silk Saree", $cat1, "55.000", "50.000", "Church Well-Wisher", "1180", "38876543", "780987654", "Traditional handloom silk with gold border"]);
        fputcsv($output, ["TAG-005", $year, "Handmade Wooden Decorative Cross", $cat5, "30.000", "25.000", "Cathedral Youth Movement", "", "", "", "Carved rosewood cross"]);

        fclose($output);
        exit;
    }

    public function import(): void {
        $user = $this->requireAuth();
        $input = $this->getJsonInput();
        $rows = [];
        $updateExisting = !empty($input['update_existing']);

        // Check if rows passed as JSON array
        if (!empty($input['rows']) && is_array($input['rows'])) {
            $rows = $input['rows'];
        } elseif (isset($_FILES['file']) && $_FILES['file']['error'] === UPLOAD_ERR_OK) {
            // Handle uploaded CSV file directly
            $tmpPath = $_FILES['file']['tmp_name'];
            $handle = fopen($tmpPath, 'r');
            if ($handle !== false) {
                $rawHeaders = fgetcsv($handle);
                if ($rawHeaders) {
                    $headerMap = [];
                    foreach ($rawHeaders as $i => $h) {
                        $clean = strtolower(trim(preg_replace('/[\s\-\#\(\)\/]+/', '_', $h)));
                        $headerMap[$i] = $clean;
                    }

                    while (($data = fgetcsv($handle)) !== false) {
                        if (empty(array_filter($data))) continue;
                        $row = [
                            'article_number'  => '',
                            'tag_number'      => '',
                            'applicable_year' => (int)date('Y'),
                            'article_name'    => '',
                            'category'        => 'General',
                            'estimated_value' => 0,
                            'reserve_price'   => 0,
                            'donor_name'      => '',
                            'donor_code_c'    => '',
                            'donor_phone'     => '',
                            'donor_cpr'       => '',
                            'description'     => ''
                        ];

                        foreach ($data as $i => $rawVal) {
                            $cleanKey = $headerMap[$i] ?? '';
                            $val = trim((string)$rawVal);
                            if (strcasecmp($val, 'N/A') === 0 || $val === '-') $val = '';

                            if (strpos($cleanKey, 'tag') !== false) {
                                $row['tag_number'] = $val;
                            } elseif (strpos($cleanKey, 'article_no') !== false || strpos($cleanKey, 'article_num') !== false || strpos($cleanKey, 'art_no') !== false || $cleanKey === 'article') {
                                $row['article_number'] = $val;
                            } elseif (strpos($cleanKey, 'year') !== false) {
                                $y = (int)$val;
                                if ($y > 2000) $row['applicable_year'] = $y;
                            } elseif (strpos($cleanKey, 'reserve') !== false || strpos($cleanKey, 'res_price') !== false || strpos($cleanKey, 'min_bid') !== false) {
                                $row['reserve_price'] = (float)$val;
                            } elseif (strpos($cleanKey, 'estimated') !== false || strpos($cleanKey, 'est_val') !== false || strpos($cleanKey, 'value') !== false || strpos($cleanKey, 'price') !== false) {
                                $row['estimated_value'] = (float)$val;
                            } elseif (strpos($cleanKey, 'roll') !== false || strpos($cleanKey, 'code_c') !== false || strpos($cleanKey, 'member_code') !== false || strpos($cleanKey, 'donor_code') !== false) {
                                $row['donor_code_c'] = $val;
                            } elseif (strpos($cleanKey, 'phone') !== false || strpos($cleanKey, 'contact') !== false || strpos($cleanKey, 'mobile') !== false) {
                                $row['donor_phone'] = $val;
                            } elseif (strpos($cleanKey, 'cpr') !== false) {
                                $row['donor_cpr'] = $val;
                            } elseif (strpos($cleanKey, 'donor') !== false || strpos($cleanKey, 'contributor') !== false || strpos($cleanKey, 'member_name') !== false) {
                                $row['donor_name'] = $val;
                            } elseif (strpos($cleanKey, 'category') !== false || strpos($cleanKey, 'cat') !== false) {
                                $row['category'] = !empty($val) ? $val : 'General';
                            } elseif (strpos($cleanKey, 'desc') !== false || strpos($cleanKey, 'remark') !== false || strpos($cleanKey, 'note') !== false) {
                                $row['description'] = $val;
                            } elseif (strpos($cleanKey, 'name') !== false || strpos($cleanKey, 'title') !== false || strpos($cleanKey, 'item') !== false) {
                                $row['article_name'] = $val;
                            }
                        }

                        if (!empty($row['article_name']) || !empty($row['tag_number'])) {
                            $rows[] = $row;
                        }
                    }
                }
                fclose($handle);
            }
        }

        if (empty($rows)) {
            $this->jsonResponse(['success' => false, 'error' => 'No valid article rows found in file.'], 400);
        }

        try {
            $result = $this->articleModel->batchImport($rows, $user['user_id'], $updateExisting);
            
            $summaryParts = [];
            if (!empty($result['imported'])) $summaryParts[] = "{$result['imported']} new article(s) created";
            if (!empty($result['updated']))  $summaryParts[] = "{$result['updated']} existing article(s) updated";
            if (!empty($result['skipped']))  $summaryParts[] = "{$result['skipped']} skipped";
            $summaryText = !empty($summaryParts) ? implode(', ', $summaryParts) . '.' : 'No changes applied.';

            $this->jsonResponse([
                'success'  => true,
                'message'  => "Import completed: {$summaryText}",
                'imported' => $result['imported'],
                'updated'  => $result['updated'],
                'skipped'  => $result['skipped'],
                'errors'   => $result['errors']
            ]);
        } catch (\Exception $e) {
            $this->jsonResponse(['success' => false, 'error' => $e->getMessage()], 500);
        }
    }
}

